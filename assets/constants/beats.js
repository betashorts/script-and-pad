// Helper function to get all beats in a flat array
export function getAllBeats(formatBeatName) {
  return Object.values(BEAT_CATEGORIES)
    .flat()
    .map((beat) => ({
      ...beat,
      name: formatBeatName ? formatBeatName(beat.file) : beat.name,
    }));
}
